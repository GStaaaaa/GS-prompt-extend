# 下拉框里显示的选项（值 -> 中文标签）
MODE_CHOICES = [f"{key}｜{info['label']}：{info['desc']}" for key, info in H3_MODES.items()]


def 解析模式选项(选项值: str) -> str:
    """从下拉选项字符串里取出模式 key；若已经是 key 则直接返回。"""
    if 选项值 in H3_MODES:
        return 选项值
    return str(选项值).split("｜")[0].strip()


def 取规则(mode: str) -> str:
    """按模式 key 取 system prompt。未知模式回落到 full_ref。"""
    key = 解析模式选项(mode)
    if key not in H3_MODES:
        log_unknown_mode(mode)
        key = "full_ref"
    return H3_MODES[key]["rule"]


def 取字段(mode: str) -> list[str]:
    key = 解析模式选项(mode)
    return H3_MODES.get(key, H3_MODES["full_ref"])["fields"]


def log_unknown_mode(mode: str) -> None:
    print(f"[GS-prompt-extend] 未知 H3 模式「{mode}」，已回落为 full_ref。", flush=True)


# ============================================================ 外部规则覆盖（可选）

def 尝试加载外部规则(mode: str, 目录: str | None = None) -> str | None:
    """
    可选能力：如果插件目录下存在 rules/<mode>.txt，就用它覆盖内置规则。
    方便不想改 Python 的人直接编辑纯文本文件。
    """
    try:
        base = 目录 or os.path.join(os.path.dirname(os.path.abspath(__file__)), "rules")
        key = 解析模式选项(mode)
        path = os.path.join(base, f"{key}.txt")
        if os.path.isfile(path):
            with open(path, "r", encoding="utf-8") as f:
                content = f.read().strip()
            if content:
                print(f"[GS-prompt-extend] 已加载外部规则文件：{path}", flush=True)
                return content
    except Exception as e:
        print(f"[GS-prompt-extend] 读取外部规则失败（忽略，使用内置规则）：{e}", flush=True)
    return None


def 取最终规则(mode: str, 允许外部覆盖: bool = True) -> str:
    if 允许外部覆盖:
        external = 尝试加载外部规则(mode)
        if external:
            return external
    return 取规则(mode)


def 按秒数改写时长(规则: str, 秒数: int) -> str:
    """
    把规则里写死的 6 秒时间轴，按比例缩放到用户指定的秒数 N。
    只动时间刻度（X-Y秒 / X秒），不动正文；「第N秒」这类用负向后顾排除，避免误缩放。
    默认 6 时原样返回，保证行为完全不变。
    """
    try:
        n = max(1, int(秒数))
    except Exception:
        n = 6
    if n == 6:
        return 规则

    scale = n / 6.0

    def _fmt(x: float) -> str:
        r = x * scale
        if abs(r - round(r)) < 1e-6:
            return str(int(round(r)))
        return f"{r:.1f}"

    def _range(m):
        return f"{_fmt(float(m.group(1)))}-{_fmt(float(m.group(2)))}秒"

    def _single(m):
        return f"{_fmt(float(m.group(1)))}秒"

    # 先缩放范围（X-Y秒），再处理独立 X秒（排除「第X秒」、以及范围刚生成的边界数字）。
    text = re.sub(r"(\d+(?:\.\d+)?)\s*-\s*(\d+(?:\.\d+)?)\s*秒", _range, 规则)
    text = re.sub(r"(?<!第)(?<!-)(?<![\d.])(\d+(?:\.\d+)?)\s*秒(?![\u4e00-\u9fff])", _single, text)
    text = (
        f"【总时长 = {n} 秒，所有时间节拍必须以 {n} 秒为总时间轴拆分，"
        f"不得出现超过 {n} 秒的内容。】\n" + text
    )
    return text
